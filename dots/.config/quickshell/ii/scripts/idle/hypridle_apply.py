#!/usr/bin/env python3
"""Writes ~/.config/hypr/hypridle.conf from the shell's idle settings, and restarts hypridle.

  hypridle_apply.py '<json of Config.options.idle>'     apply
  hypridle_apply.py --print '<json>'                    print the file, change nothing

The fixed part (lock command, lock before suspend, releasing the fingerprint reader before
sleep) is the same for everyone and is not configurable: a wrong setting must not be able to
suspend the laptop unlocked. Only the idle steps come from the settings.

Idempotent: if the generated text equals the file, nothing is written and hypridle is left
running, so applying the same settings at every login costs nothing. The first time, the
file that was there is kept as hypridle.conf.before-settings.

Standard library only. Environment: II_HYPRIDLE_CONF (target file), II_HYPRIDLE_NO_RESTART=1.
"""
from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
import time

MARKER = "# Generated by the shell: Settings > Power & Battery > When idle. Edits here are overwritten."

HEADER = """$lock_cmd = pidof qs quickshell >/dev/null && hyprctl dispatch 'hl.dsp.global("quickshell:lock")' || ~/.config/hypr/hyprlock/lockscreen

general {
	lock_cmd = $lock_cmd
	inhibit_sleep = 3
	# Release an in-flight fingerprint read first: suspending mid-read crashes some readers' drivers.
	before_sleep_cmd = hyprctl dispatch 'hl.dsp.global("quickshell:lockFingerStop")' ; loginctl lock-session     # lock before suspend.
	after_sleep_cmd = hyprctl dispatch 'hl.dsp.global("quickshell:lockFocus")'
}
"""

DPMS_OFF = """hyprctl dispatch 'hl.dsp.dpms({ action = "off" })'"""
DPMS_ON = """hyprctl dispatch 'hl.dsp.dpms({ action = "on" })'"""
BRIGHTNESS_NOW = """$(brightnessctl -m | cut -d "," -f4 | tr -d "%")"""

# The defaults are what the machine had before this was a setting.
DEFAULTS = {
    "dim": {"enable": False, "seconds": 120},
    "lowerBrightness": {"enable": True, "seconds": 300},
    "screenOffLocked": {"enable": True, "seconds": 60},
    "lock": {"enable": True, "seconds": 600},
    "screenOff": {"enable": True, "seconds": 602},
    "suspend": {"enable": True, "seconds": 1200, "onlyOnBattery": True},
}


def seconds_of(step: dict, default: int) -> int:
    try:
        value = int(float(step.get("seconds", default)))
    except (TypeError, ValueError):
        value = default
    return max(10, min(86400, value))


def listener(timeout: int, on_timeout: str, on_resume: str = "") -> str:
    lines = ["listener {", f"\ttimeout = {timeout}", f"\ton-timeout = {on_timeout}"]
    if on_resume:
        lines.append(f"\ton-resume = {on_resume}")
    lines.append("}")
    return "\n".join(lines)


def build(settings: dict) -> str:
    cfg = {name: {**base, **(settings.get(name) or {})} for name, base in DEFAULTS.items()}
    steps = []  # (timeout, text)

    def add(name: str, make) -> None:
        step = cfg[name]
        if step.get("enable"):
            timeout = seconds_of(step, DEFAULTS[name]["seconds"])
            steps.append((timeout, make(timeout, step)))

    add("dim", lambda t, s: listener(
        t, "qs ipc -c ii call idleDim dim", "qs ipc -c ii call idleDim restore"))
    add("lowerBrightness", lambda t, s: listener(
        t,
        f'if [[ "{BRIGHTNESS_NOW}" -ge "20" ]]; then brightnessctl s 20%- ;fi',
        f'if [[ "{BRIGHTNESS_NOW}" -ge "20" ]]; then brightnessctl s 20%+ ;fi'))
    add("screenOffLocked", lambda t, s: listener(
        t, f'if [ "$(qs -c ii ipc call lock locked 2>/dev/null)" = true ]; then {DPMS_OFF}; fi', DPMS_ON))
    add("lock", lambda t, s: listener(t, "loginctl lock-session", DPMS_ON))
    add("screenOff", lambda t, s: listener(t, DPMS_OFF, DPMS_ON))

    def suspend(t: int, s: dict) -> str:
        if s.get("onlyOnBattery"):
            # An adapter that reads online=1 means plugged in; see the lid binds for the same test.
            return listener(t, "! grep -qx 1 /sys/class/power_supply/*/online && systemctl suspend")
        return listener(t, "systemctl suspend")
    add("suspend", suspend)

    steps.sort(key=lambda item: item[0])
    body = "\n\n".join(text for _, text in steps)
    return f"{MARKER}\n{HEADER}\n{body}\n" if body else f"{MARKER}\n{HEADER}"


def target_path() -> str:
    return os.environ.get("II_HYPRIDLE_CONF") or os.path.expanduser("~/.config/hypr/hypridle.conf")


def hypridle_running() -> bool:
    return subprocess.run(["pgrep", "-x", "hypridle"], capture_output=True).returncode == 0


def restart_hypridle() -> None:
    if subprocess.run(["systemctl", "--user", "-q", "is-active", "hypridle.service"],
                      capture_output=True).returncode == 0:
        subprocess.run(["systemctl", "--user", "restart", "hypridle.service"], check=False)
        return
    subprocess.run(["pkill", "-x", "hypridle"], check=False)
    for _ in range(20):
        if not hypridle_running():
            break
        time.sleep(0.1)
    subprocess.Popen(["hypridle"], stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                     stderr=subprocess.DEVNULL, start_new_session=True)


def main(argv: list) -> int:
    print_only = bool(argv) and argv[0] == "--print"
    if print_only:
        argv = argv[1:]
    try:
        settings = json.loads(argv[0]) if argv else {}
        if not isinstance(settings, dict):
            raise ValueError("settings must be an object")
    except ValueError as error:
        print(f"ERROR bad settings: {error}", file=sys.stderr)
        return 2
    text = build(settings)
    if print_only:
        print(text, end="")
        return 0
    path = target_path()
    try:
        current = open(path, encoding="utf-8").read()
    except OSError:
        current = None
    if current == text:
        print("unchanged")
        return 0
    if current is not None and MARKER not in current:
        backup = path + ".before-settings"
        if not os.path.exists(backup):
            shutil.copy2(path, backup)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as handle:
        handle.write(text)
    os.replace(tmp, path)
    if os.environ.get("II_HYPRIDLE_NO_RESTART") != "1" and hypridle_running():
        restart_hypridle()
        print("applied, hypridle restarted")
    else:
        print("applied")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
